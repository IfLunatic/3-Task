package ua.kpi.hpc.common;

/**
 * Генератор даних для бенчмарків паралельних обчислень.
 *
 * Створює масиви зі стандартним шаблоном: елемент із індексом i має значення (i % 100) + 1.
 * Значення лежать у діапазоні від 1 до 100 включно.
 *
 * Однакова логіка генерації використовується в Java- та Go-реалізаціях,
 * щоб результати завжди збігалися і їх можна було порівнювати.
 */
public final class DataGenerator {

    // Заборонений конструктор — утилітний клас (не треба створювати об'єкти)
    private DataGenerator() {}

    /**
     * Створює новий масив заданого розміру та заповнює його стандартним шаблоном.
     *
     * @param size кількість елементів масиву
     * @return заповнений масив типу long[]
     */
    public static long[] generate(int size) {
        long[] array = new long[size];
        fill(array);
        return array;
    }

    /**
     * Заповнює існуючий масив шаблоном (i % 100) + 1 на місці (in-place).
     *
     * Використовується перед кожним прогоном хвильового алгоритму,
     * тому що хвиля змінює масив на місці, і дані потрібно відновити
     * без повторного виділення пам'яті.
     *
     * @param array масив для заповнення
     */
    public static void fill(long[] array) {
        for (int i = 0; i < array.length; i++) {
            array[i] = (i % 100) + 1;
        }
    }

    /**
     * Обчислює точну аналітичну суму масиву довжиною size.
     *
     * Шаблон повторюється з періодом 100. Сума чисел від 1 до 100 = 5050.
     * Для залишку обчислюємо суму арифметичної прогресії.
     *
     * @param size довжина масиву
     * @return очікувана математична сума (для перевірки правильності алгоритмів)
     */
    public static long expectedSum(long size) {
        if (size <= 0) {
            return 0L;
        }
        long fullCycles = size / 100;         // кількість повних циклів (1..100)
        long remainder = size % 100;          // елементи, що не вклалися в повний цикл
        long sumFromCycles = fullCycles * 5050L;                   // сума повних циклів
        long sumFromRemainder = (remainder * (remainder + 1)) / 2; // сума залишку: 1+2+...+remainder
        return sumFromCycles + sumFromRemainder;
    }
}
