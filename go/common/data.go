// Пакет common — генератор даних та аналітичні функції.
// Містить єдину логіку створення масивів для Java та Go реалізацій.
package common

// Generate створює та повертає зріз (slice) типу int64 заданого розміру.
// Кожен елемент із індексом i має значення (i % 100) + 1 (від 1 до 100).
func Generate(size int) []int64 {
	array := make([]int64, size)
	Fill(array)
	return array
}

// Fill заповнює існуючий зріз на місці (in-place) стандартним шаблоном.
// Використовується перед кожним прогоном хвильового алгоритму,
// тому що хвиля модифікує масив і дані треба відновити.
func Fill(array []int64) {
	for i := 0; i < len(array); i++ {
		array[i] = int64((i % 100) + 1)
	}
}

// ExpectedSum обчислює точну аналітичну суму масиву довжиною size.
// Шаблон повторюється з періодом 100. Сума 1+2+...+100 = 5050.
// Для залишку обчислюємо суму арифметичної прогресії: remainder*(remainder+1)/2.
func ExpectedSum(size int64) int64 {
	if size <= 0 {
		return 0
	}
	fullCycles := size / 100          // кількість повних циклів (1..100)
	remainder := size % 100           // елементи, що не вклалися у повний цикл
	return (fullCycles * 5050) + (remainder * (remainder + 1) / 2)
}
